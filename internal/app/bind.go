// bind.go is the actual mygo.Bind target.
//
// Why a separate type instead of binding *App directly: mygo.Bind
// exposes every exported method of the bound value, and Bind panics
// when a method uses a type JSON cannot encode. *App has such methods
// (Events() *EventBus, Mount() (MountHandle, bool), ProviderFor()).
// DesktopService exposes only the JSON-safe UI surface, one method
// per user action, all delegating to the App layer. The frontend
// never calls drivers or cloud APIs directly.
//
// The TypeScript client is generated by `mygo generate` into
// frontend/src/mygo.ts from this type; regenerate after changing it.
// Method names are stable: renaming one breaks the generated client.

// DesktopService is the mygo.Bind service for the desktop frontend.
type DesktopService struct {
	app *App
}

// BindService returns the service bound to the frontend.
func (a *App) BindService() *DesktopService { return &DesktopService{app: a} }

// ListMounts returns mounts for the sidebar.
func (s *DesktopService) ListMounts() []*domain.Mount { return s.app.ListMounts() }

// Browse lists a directory (cache-first, background refresh).
func (s *DesktopService) Browse(ctx context.Context, mountID, ref string) ([]domain.Node, error) {
	return s.app.Browse(ctx, mountID, ref)
}

// SearchResult is the single return value of DesktopService.Search.
// mygo.Bind allows at most one value plus an error, so the
// (nodes, localOnly) pair is wrapped in this struct.
type SearchResult struct {
	Nodes     []domain.Node `json:"nodes"`
	LocalOnly bool          `json:"localOnly"`
}

// Search searches a mount. LocalOnly reports "本地结果".
func (s *DesktopService) Search(ctx context.Context, mountID, query string) (*SearchResult, error) {
	nodes, localOnly, err := s.app.Search(ctx, mountID, query)
	if err != nil {
		return nil, err
	}
	return &SearchResult{Nodes: nodes, LocalOnly: localOnly}, nil
}

